// ===== LANGUAGE MANAGER =====
const LangManager = {

  current: 'en',

  init() {
    const saved = localStorage.getItem('gr_lang') || 'en';
    this.current = saved;
    // Set select dropdown if present
    const sel = document.getElementById('lang-selector');
    if (sel) sel.value = saved;
    this.applyAll();
  },

  set(lang) {
    this.current = lang;
    localStorage.setItem('gr_lang', lang);
    this.applyAll();
  },

  t(key) {
    const dict = TRANSLATIONS[this.current] || TRANSLATIONS.en;
    return dict[key] || TRANSLATIONS.en[key] || key;
  },

  applyAll() {
    // Apply to all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const attr = el.getAttribute('data-i18n-attr');
      if (attr) {
        el.setAttribute(attr, this.t(key));
      } else {
        el.textContent = this.t(key);
      }
    });
    // Update html lang attribute
    const langMap = { en:'en', hi:'hi', mr:'mr' };
    document.documentElement.lang = langMap[this.current] || 'en';
  }
};

// Shorthand helper
function t(key) { return LangManager.t(key); }
